"""Regenerate byte contracts from durable, independently frozen Sky originals."""
import argparse
import hashlib
import json
from pathlib import Path


def generate(root):
    roots=json.loads((root/'tests/fixtures/battle_root_originals.json').read_text())
    collections=json.loads((root/'tests/fixtures/battle_collection_originals.json').read_text())
    output=['// Generated by tools/generate_battle_profiles.py from durable original fixtures.',
            '// These are read-contract checks, not approved native call entries.']
    for game,label in [('sky1','first'),('sky2','second')]:
        row=next(r for r in collections if r['game']==game)
        original=next(r for r in roots if r['game']==game)
        if row['executable_sha256']!=original['executable_sha256']:raise ValueError('Fixture executable mismatch')
        constructor=next(f for f in original['fragments'] if f['rva']==original['constructor'])
        fragments=[dict(rva=hex(constructor['rva']),code_hex=constructor['hex'],body_sha256=constructor['sha256'])]
        fragments += [next(f for f in row['fragments'] if f['name']==name) for name in
                      ('append','entry_constructor','remove','entry_teardown','primary_dispatch','field_active','field_dispatch')]
        output.append(f'inline constexpr Code {label}_codes[]={{')
        for f in fragments:
            data=bytes.fromhex(f['code_hex'])
            if not data or len(data)>4096 or hashlib.sha256(data).hexdigest()!=f['body_sha256']:raise ValueError('Invalid original fragment')
            output.append(f'    {{{f["rva"]},"{f["code_hex"]}"}},')
        output.append('};')
    return '\n'.join(output)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();root=Path(__file__).resolve().parents[1]
    target=root/'src/windows/battle_profiles.inc';text=generate(root)
    if args.check:
        if target.read_text()!=text:raise SystemExit('Battle byte profiles differ from durable originals')
    else:target.write_text(text)
